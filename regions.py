def norm(value: str) -> str:
    return re.sub(r'[^а-яa-z0-9]+', ' ', (value or '').casefold().replace('ё','е')).strip()

def genitive(stem: str) -> str:
    """Common adjective district names appear in genitive case on MГИК pages."""
    replacements=(('ский','ского'),('цкий','цкого'),('ской','ского'),('ный','ного'),('ний','него'),('ый','ого'),('ий','его'))
    for src,dst in replacements:
        if stem.endswith(src): return stem[:-len(src)]+dst
    return stem

def lookup(name: str) -> str:
    n=norm(name)
    n=re.sub(r'^территориальная избирательная комиссия\s+', '', n)
    n=re.sub(r'^тик\s+', '', n)
    n=re.sub(r'^района\s+', '', n)
    n=re.sub(r'\s+района$', '', n)
    n=norm(n)
    for ao, raw in DISTRICTS.items():
        names=[norm(x) for x in raw.split(';')]
        if n in names or n in [genitive(x) for x in names]:
            return ao
    return 'Не определён'
